-- views
CREATE TABLE base (id int PRIMARY KEY, kind text, n int);
INSERT INTO base VALUES (1, 'a', 10), (2, 'b', 20), (3, 'a', 30);
CREATE VIEW v_a AS SELECT id, n FROM base WHERE kind = 'a';
SELECT * FROM v_a ORDER BY id;
CREATE VIEW v_sum (kind, total) AS SELECT kind, sum(n) FROM base GROUP BY kind;
SELECT * FROM v_sum ORDER BY kind;
SELECT v_a.id, v_sum.total FROM v_a JOIN base b ON b.id = v_a.id JOIN v_sum ON v_sum.kind = b.kind ORDER BY 1;
