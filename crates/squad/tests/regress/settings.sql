-- Custom settings (names with a dot), SET LOCAL, set_config and
-- current_setting, and how transactions undo setting changes.
SHOW app.tenant;
SELECT current_setting('app.tenant');
SELECT current_setting('app.tenant', true) IS NULL AS unset;
SET app.tenant = 'acme';
SHOW app.tenant;
SELECT current_setting('app.tenant'), current_setting('app.tenant', false);
SET app.tenant TO 'globex';
SHOW app.tenant;
-- reset keeps the setting, empty
RESET app.tenant;
SHOW app.tenant;
SELECT current_setting('app.tenant', true) IS NULL AS unset, current_setting('app.tenant') = '' AS empty;
SET app.tenant TO DEFAULT;
SHOW app.tenant;
SET app.count = 42;
SHOW app.count;
SET app.flag = on;
SHOW app.flag;
SET app.list = 'a', 'b';
SET SESSION app.tenant = 'acme';
SHOW app.tenant;
-- names without a dot are not custom settings
SELECT current_setting('no_such_setting');
SELECT current_setting('no_such_setting', true);
SELECT current_setting('app.never.set', true);
SELECT current_setting(NULL);
-- SET in a transaction that rolls back is undone
BEGIN;
SET app.tenant = 'initech';
SHOW app.tenant;
ROLLBACK;
SHOW app.tenant;
BEGIN;
SET app.tenant = 'initech';
COMMIT;
SHOW app.tenant;
-- SET LOCAL lasts until the transaction ends
BEGIN;
SET LOCAL app.tenant = 'local';
SHOW app.tenant;
SELECT current_setting('app.tenant');
COMMIT;
SHOW app.tenant;
BEGIN;
SET LOCAL app.tenant = 'local';
ROLLBACK;
SHOW app.tenant;
BEGIN;
SET app.tenant = 'session';
SET LOCAL app.tenant = 'local';
SHOW app.tenant;
COMMIT;
SHOW app.tenant;
BEGIN;
SET LOCAL app.tenant = 'local';
SET app.tenant = 'session2';
SHOW app.tenant;
COMMIT;
SHOW app.tenant;
-- SET LOCAL outside a transaction block has no effect
SET LOCAL app.tenant = 'ignored';
SHOW app.tenant;
SET LOCAL app.other = 'ignored';
SHOW app.other;
-- savepoints
BEGIN;
SET app.tenant = 't1';
SAVEPOINT a;
SET app.tenant = 't2';
SHOW app.tenant;
ROLLBACK TO SAVEPOINT a;
SHOW app.tenant;
SAVEPOINT b;
SET LOCAL app.tenant = 't3';
RELEASE SAVEPOINT b;
SHOW app.tenant;
COMMIT;
SHOW app.tenant;
BEGIN;
SAVEPOINT a;
SET app.tenant = 't4';
ROLLBACK TO a;
SHOW app.tenant;
SET app.tenant = 't5';
COMMIT;
SHOW app.tenant;
-- an error aborts the transaction; its settings are undone
BEGIN;
SET app.tenant = 'doomed';
SELECT 1 / 0;
COMMIT;
SHOW app.tenant;
