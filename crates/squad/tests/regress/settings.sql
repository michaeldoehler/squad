SHOW app.tenant;
SELECT set_config('app.fresh', 'x', true);
SHOW app.fresh;
BEGIN;
SELECT set_config('app.tenant', 'in_txn', true);
SELECT current_setting('app.tenant');
SELECT current_setting('app.tenant');
COMMIT;
SHOW app.tenant;
BEGIN;
SELECT set_config('app.tenant', 'rolled_back', false);
ROLLBACK;
SHOW app.tenant;
SELECT set_config('app.tenant', NULL, false);
SHOW app.tenant;
SELECT set_config(NULL, 'x', false);
SELECT set_config('app.tenant', 'acme', false) AS a, current_setting('app.tenant') AS b;
-- a failing statement undoes its set_config
SELECT set_config('app.tenant', 'failed', false), 1 / 0;
SHOW app.tenant;
-- the same setting in WHERE clauses and with parameters
