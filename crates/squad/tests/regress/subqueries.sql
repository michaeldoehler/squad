-- Subqueries, EXISTS, IN, ANY/ALL and set operations.
CREATE TABLE t1 (a int PRIMARY KEY, b text);
CREATE TABLE t2 (x int, y int);
INSERT INTO t1 VALUES (1, 'one'), (2, 'two'), (3, 'three'), (4, NULL);
INSERT INTO t2 VALUES (1, 10), (1, 11), (2, 20), (NULL, 99), (5, 50);
SELECT a FROM t1 WHERE a IN (SELECT x FROM t2) ORDER BY a;
SELECT a FROM t1 WHERE a NOT IN (SELECT x FROM t2 WHERE x IS NOT NULL) ORDER BY a;
SELECT a FROM t1 WHERE a NOT IN (SELECT x FROM t2) ORDER BY a;
SELECT a FROM t1 WHERE EXISTS (SELECT 1 FROM t2 WHERE t2.x = t1.a) ORDER BY a;
SELECT a FROM t1 WHERE NOT EXISTS (SELECT 1 FROM t2 WHERE t2.x = t1.a) ORDER BY a;
SELECT a, (SELECT count(*) FROM t2 WHERE t2.x = t1.a) AS n FROM t1 ORDER BY a;
SELECT a, (SELECT max(y) FROM t2 WHERE t2.x = t1.a) FROM t1 ORDER BY a;
SELECT (SELECT b FROM t1 WHERE a = 2), (SELECT b FROM t1 WHERE a = 99);
SELECT a FROM t1 WHERE a > (SELECT avg(x) FROM t2) ORDER BY a;
SELECT a FROM t1 WHERE a = ANY (SELECT x FROM t2) ORDER BY a;
SELECT a FROM t1 WHERE a > ALL (SELECT x FROM t2 WHERE x < 3) ORDER BY a;
SELECT a FROM t1 WHERE a < ANY (SELECT x FROM t2) ORDER BY a;
SELECT a FROM t1 WHERE (a, b) IN (SELECT 1, 'one' UNION ALL SELECT 2, 'zwei') ORDER BY a;
SELECT a, ARRAY(SELECT y FROM t2 WHERE x = a ORDER BY y) FROM t1 ORDER BY a;
SELECT * FROM (SELECT a, b FROM t1 WHERE a < 3) s WHERE s.b LIKE 't%';
SELECT x.a FROM (SELECT a FROM t1 ORDER BY a DESC LIMIT 2) x ORDER BY x.a;
SELECT a FROM t1 WHERE b = (SELECT b FROM t1);
SELECT (SELECT a, b FROM t1 WHERE a = 1);
SELECT a FROM t1 UNION SELECT x FROM t2 ORDER BY 1 NULLS LAST;
SELECT a FROM t1 UNION ALL SELECT x FROM t2 ORDER BY 1 NULLS LAST;
SELECT a FROM t1 INTERSECT SELECT x FROM t2 ORDER BY 1;
SELECT x FROM t2 EXCEPT SELECT a FROM t1 ORDER BY 1 NULLS LAST;
SELECT x FROM t2 EXCEPT ALL SELECT a FROM t1 ORDER BY 1 NULLS LAST;
SELECT x FROM t2 INTERSECT ALL SELECT x FROM t2 WHERE x = 1 ORDER BY 1;
(SELECT a FROM t1 ORDER BY a LIMIT 2) UNION ALL (SELECT a FROM t1 ORDER BY a DESC LIMIT 1) ORDER BY 1;
SELECT a, 'x' FROM t1 WHERE a = 1 UNION SELECT 2, NULL ORDER BY 1;
SELECT 1 UNION SELECT 'a';
SELECT 1, 2 UNION SELECT 1;
SELECT 1 AS n UNION SELECT 2 UNION SELECT 1 ORDER BY n DESC;
VALUES (1, 'a'), (2, 'b') ORDER BY 1 DESC;
SELECT * FROM (VALUES (1, 'a'), (2, 'b')) AS v (n, s) WHERE n > 1;
SELECT column1 + 1 FROM (VALUES (1), (2)) v ORDER BY 1;
