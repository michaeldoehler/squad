-- Aggregation and grouping.
CREATE TABLE sales (id int PRIMARY KEY, region text, product text, qty int, price numeric(8,2), sold date);
INSERT INTO sales VALUES (1, 'north', 'apple', 10, 1.50, '2024-01-05'), (2, 'north', 'pear', 5, 2.00, '2024-01-06'), (3, 'south', 'apple', 7, 1.60, '2024-02-01'), (4, 'south', 'apple', NULL, 1.55, '2024-02-03'), (5, 'east', 'fig', 1, 9.99, '2024-03-10'), (6, NULL, 'fig', 2, 9.50, '2024-03-11');
SELECT count(*), count(qty), count(DISTINCT product), count(DISTINCT region) FROM sales;
SELECT sum(qty), avg(qty), min(qty), max(qty), sum(price), avg(price) FROM sales;
SELECT region, count(*), sum(qty) FROM sales GROUP BY region ORDER BY region NULLS FIRST;
SELECT region, product, sum(qty * price) AS revenue FROM sales GROUP BY region, product ORDER BY 1 NULLS LAST, 2;
SELECT product, count(*) FROM sales GROUP BY product HAVING count(*) > 1 ORDER BY product;
SELECT product, sum(qty) FROM sales WHERE region IS NOT NULL GROUP BY 1 HAVING sum(qty) >= 10 ORDER BY 2 DESC;
SELECT upper(product) AS p, max(price) FROM sales GROUP BY p ORDER BY p;
SELECT extract(month FROM sold) AS m, count(*) FROM sales GROUP BY m ORDER BY m;
SELECT region, string_agg(product, ',' ORDER BY product) FROM sales GROUP BY region ORDER BY region NULLS LAST;
SELECT array_agg(qty ORDER BY id), array_agg(DISTINCT product ORDER BY product) FROM sales;
SELECT bool_and(qty > 0), bool_or(qty > 9), every(price > 1) FROM sales;
SELECT count(*) FILTER (WHERE region = 'north'), sum(qty) FILTER (WHERE product = 'apple') FROM sales;
SELECT sum(qty), count(*) FROM sales WHERE false;
SELECT region, sum(qty) FROM sales WHERE false GROUP BY region;
SELECT max(sold), min(sold), max(product), min(region) FROM sales;
SELECT sum(qty)::float8 / count(*), round(avg(price), 3), stddev_pop(qty)::numeric(10,4), variance(qty)::numeric(10,4) FROM sales;
SELECT json_agg(id ORDER BY id), jsonb_object_agg(id, product ORDER BY id) FROM sales WHERE id <= 2;
SELECT s.id, s.region FROM sales s GROUP BY s.id ORDER BY s.id LIMIT 2;
SELECT DISTINCT region FROM sales ORDER BY region NULLS FIRST;
SELECT DISTINCT product, region IS NULL FROM sales ORDER BY 1, 2;
SELECT DISTINCT ON (product) product, qty, id FROM sales ORDER BY product, qty DESC NULLS LAST;
SELECT region, sum(qty) FROM sales GROUP BY region ORDER BY sum(qty) DESC NULLS LAST, region LIMIT 2;
SELECT count(*) FROM (SELECT DISTINCT region, product FROM sales) x;
SELECT product, qty FROM sales GROUP BY product;
SELECT sum(product) FROM sales;
SELECT count(*) FROM sales WHERE sum(qty) > 1;
SELECT max(sum(qty)) FROM sales;
SELECT region FROM sales GROUP BY 7;
