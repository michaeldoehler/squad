-- Joins of all kinds.
CREATE TABLE dept (id int PRIMARY KEY, name text NOT NULL);
CREATE TABLE emp (id int PRIMARY KEY, name text NOT NULL, dept_id int, salary numeric(10,2), manager_id int);
CREATE INDEX emp_dept_idx ON emp (dept_id);
