SELECT e.name, d.name FROM emp e RIGHT JOIN dept d ON d.id = e.dept_id ORDER BY d.id, e.id;
SELECT e.name, d.name FROM emp e FULL JOIN dept d ON d.id = e.dept_id ORDER BY e.id NULLS LAST, d.id;
SELECT e.name, d.name FROM emp e CROSS JOIN dept d WHERE e.id <= 2 ORDER BY e.id, d.id;
SELECT e.name, d.name FROM emp e, dept d WHERE e.dept_id = d.id AND d.name = 'ops' ORDER BY e.id;
SELECT e.name, m.name AS manager FROM emp e LEFT JOIN emp m ON m.id = e.manager_id ORDER BY e.id;
SELECT d.name, count(e.id), coalesce(sum(e.salary), 0) FROM dept d LEFT JOIN emp e ON e.dept_id = d.id GROUP BY d.name ORDER BY d.name;
SELECT e.name FROM emp e JOIN dept d ON d.id = e.dept_id AND d.name <> 'eng' ORDER BY 1;
