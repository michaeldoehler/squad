SELECT e.name, d.name FROM emp e LEFT JOIN dept d ON d.id = e.dept_id WHERE d.name IS NULL ORDER BY e.id;
SELECT a.name, b.name FROM emp a JOIN emp b ON a.salary < b.salary AND b.dept_id = a.dept_id ORDER BY a.id, b.id;
