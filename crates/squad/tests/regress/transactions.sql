-- Transaction control within one session.
CREATE TABLE acct (id int PRIMARY KEY, balance int NOT NULL CHECK (balance >= 0));
INSERT INTO acct VALUES (1, 100), (2, 50);
BEGIN;
UPDATE acct SET balance = balance - 30 WHERE id = 1;
UPDATE acct SET balance = balance + 30 WHERE id = 2;
SELECT * FROM acct ORDER BY id;
COMMIT;
SELECT * FROM acct ORDER BY id;
BEGIN;
DELETE FROM acct;
SELECT count(*) FROM acct;
ROLLBACK;
SELECT count(*) FROM acct;
-- an error aborts the transaction until rollback
BEGIN;
UPDATE acct SET balance = balance - 500 WHERE id = 1;
SELECT 1;
UPDATE acct SET balance = 0;
COMMIT;
SELECT * FROM acct ORDER BY id;
-- savepoints
BEGIN;
INSERT INTO acct VALUES (3, 1);
SAVEPOINT a;
INSERT INTO acct VALUES (4, 1);
SAVEPOINT b;
INSERT INTO acct VALUES (4, 1);
ROLLBACK TO SAVEPOINT b;
INSERT INTO acct VALUES (5, 1);
ROLLBACK TO a;
INSERT INTO acct VALUES (6, 1);
RELEASE SAVEPOINT a;
ROLLBACK TO a;
ROLLBACK;
BEGIN;
INSERT INTO acct VALUES (3, 1);
SAVEPOINT a;
INSERT INTO acct VALUES (4, 1);
ROLLBACK TO a;
COMMIT;
SELECT id FROM acct ORDER BY id;
SAVEPOINT nope;
ROLLBACK TO nope;
-- transactional DDL
BEGIN;
CREATE TABLE tmp (x int);
INSERT INTO tmp VALUES (1);
ALTER TABLE acct ADD COLUMN note text;
SELECT note FROM acct WHERE id = 1;
ROLLBACK;
SELECT * FROM tmp;
SELECT note FROM acct;
BEGIN;
DROP TABLE acct;
SELECT * FROM acct;
ROLLBACK;
SELECT count(*) FROM acct;
-- isolation levels and read only
BEGIN ISOLATION LEVEL SERIALIZABLE;
SHOW transaction_isolation;
SELECT count(*) FROM acct;
COMMIT;
BEGIN ISOLATION LEVEL REPEATABLE READ;
SHOW transaction_isolation;
ROLLBACK;
SHOW transaction_isolation;
BEGIN READ ONLY;
SELECT count(*) FROM acct;
INSERT INTO acct VALUES (9, 9);
ROLLBACK;
START TRANSACTION;
SET TRANSACTION ISOLATION LEVEL REPEATABLE READ;
SHOW transaction_isolation;
COMMIT;
